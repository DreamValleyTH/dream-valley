# Builds data.js (scene layout + sprite meta + ป้าแต๋ว lines) so the game runs from file:// without fetch.
#   python make_data.py <Dream_Valley root> <web/farm_yai dir>
import sys, json, yaml, os
ROOT, OUT = sys.argv[1], sys.argv[2]
scene = json.load(open(os.path.join(OUT, 'tools/scene.json'), encoding='utf-8'))
meta = json.load(open(os.path.join(OUT, 'tools/meta.json'), encoding='utf-8'))
y = yaml.safe_load(open(os.path.join(ROOT, 'docs/dialogue/taew.yaml'), encoding='utf-8'))
keep = ['greet_morning', 'greet_noon', 'greet_evening', 'greet_night', 'weather_rain', 'heart_low', 'heart_mid', 'heart_high',
        'topic_news', 'topic_advice', 'topic_smalltalk', 'topic_about_self', 'topic_about_others', 'gift_like', 'gift_neutral', 'player_fainted', 'rare']
lines = {k: y['lines'][k] for k in keep if k in y.get('lines', {})}
taew = dict(id=y.get('id'), name=y.get('name'), role=y.get('role'), lines=lines, gifts=y.get('gifts', {}),
            convos=y.get('convos', []), choices=y.get('choices', []))   # บทคุยโต้ตอบ + บทมีตัวเลือกเดิม
with open(os.path.join(OUT, 'data.js'), 'w', encoding='utf-8') as f:
    f.write('// generated by tools/make_data.py — do not edit by hand\n')
    f.write('window.DV_SCENE=' + json.dumps(scene, ensure_ascii=False) + ';\n')
    f.write('window.DV_META=' + json.dumps(meta, ensure_ascii=False) + ';\n')
    f.write('window.DV_TAEW=' + json.dumps(taew, ensure_ascii=False) + ';\n')
print('ok', {k: len(v) for k, v in lines.items()}, 'convos', len(taew['convos']), 'choices', len(taew['choices']))
