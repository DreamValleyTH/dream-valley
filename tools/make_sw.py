# Writes sw.js: an offline cache of every game file (run after any build, before pushing to GitHub)
import os, json, hashlib, sys
ROOT = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
files = []
for d, _, fs in os.walk(ROOT):
    rel = os.path.relpath(d, ROOT)
    if rel.startswith(('tools', '.git', 'content', 'assets_src')) or '/.' in rel: continue
    for f in fs:
        if f.endswith(('.py', '.md', '.json')) and f != 'manifest.webmanifest': continue
        if f in ('sw.js', 'artifact.html', 'game.js', 'data.js') or f.startswith('.'): continue
        files.append(os.path.normpath(os.path.join(rel, f)).replace('\\', '/'))
h = hashlib.md5()
for f in sorted(files): h.update(open(os.path.join(ROOT, f), 'rb').read())
ver = h.hexdigest()[:10]
files = ['./'] + sorted(files)
open(os.path.join(ROOT, 'sw.js'), 'w').write(f"""// generated by tools/make_sw.py — offline cache for the installed app
const V = 'dv-{ver}', FILES = {json.dumps(files)};
self.addEventListener('install', e => {{ e.waitUntil(caches.open(V).then(c => c.addAll(FILES)).then(() => self.skipWaiting())); }});
self.addEventListener('activate', e => {{ e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k !== V).map(k => caches.delete(k)))).then(() => self.clients.claim())); }});
self.addEventListener('fetch', e => {{ if (e.request.method !== 'GET' || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(caches.match(e.request, {{ ignoreSearch: true }}).then(r => r || fetch(e.request).then(res => {{ const c = res.clone(); caches.open(V).then(x => x.put(e.request, c)); return res; }}))); }});
""")
print('sw.js', ver, len(files), 'files')
